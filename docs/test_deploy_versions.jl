using Test
using Documenter
using DocumenterVitepress

include(joinpath(@__DIR__, "deploy_versions.jl"))

@testset "versions.js generation" begin
    mktempdir() do root
        folders = ["dev", "stable", "v1", "v1.5", "v1.5.9", "v2.0.0", "v2.0.0a2", "v2.1.0"]
        foreach(folder -> mkpath(joinpath(root, folder)), folders)

        for folder in ["v1.5.9", "v2.0.0", "v2.1.0"]
            write(
                joinpath(root, folder, "siteinfo.js"),
                "var DOCUMENTER_CURRENT_VERSION = \"$folder\";\n",
            )
        end

        Documenter.postprocess_before_push(
            PySRVersions("v2.1.0");
            subfolder = "v2.1.0",
            devurl = "dev",
            deploy_dir = joinpath(root, "v2.1.0"),
            dirname = "",
        )

        versions = read(joinpath(root, "versions.js"), String)
        expected = """var DOC_VERSIONS = [
  \"dev\",
  \"stable\",
  \"v2.1.0\",
  \"v2.0.0\",
  \"v1.5.9\",
  \"v1.5\",
  \"v1\",
];
var DOCUMENTER_NEWEST = \"2.1.0\";
var DOCUMENTER_STABLE = \"stable\";
"""
        @test versions == expected
        @test !occursin("v2.0.0a2", versions)
        @test read(joinpath(root, "index.html"), String) == """<!--This file is automatically generated by docs/deploy.jl-->
<meta http-equiv="refresh" content="0; url=./stable/"/>
"""
    end
end

@testset "gh-pages root derivation" begin
    for base in ["v2.1.0", "previews/PR123", "PR(1)"]
        mktempdir() do root
            mkpath(joinpath(root, "stable"))
            mkpath(joinpath(root, "v2.1.0"))
            write(
                joinpath(root, "v2.1.0", "siteinfo.js"),
                "var DOCUMENTER_CURRENT_VERSION = \"v2.1.0\";\n",
            )
            deploy_dir = joinpath(root, base)
            mkpath(deploy_dir)

            Documenter.postprocess_before_push(
                PySRVersions(base);
                subfolder = base,
                devurl = "dev",
                deploy_dir = deploy_dir,
                dirname = "",
            )

            # The version list belongs at the gh-pages root, never inside the deployed base
            @test isfile(joinpath(root, "versions.js"))
            @test occursin("\"v2.1.0\"", read(joinpath(root, "versions.js"), String))
            @test !isfile(joinpath(deploy_dir, "versions.js"))
        end
    end
end

@testset "alias bases" begin
    tagged_versions = [v"2.1.0", v"2.0.0", v"1.5.10"]

    @test deploy_bases(
        "v2.1.0";
        all_tagged_versions = tagged_versions,
    ) == ["v2.1.0", "stable", "v2", "v2.1"]

    older_bases = deploy_bases(
        "v1.5.10";
        all_tagged_versions = tagged_versions,
    )
    @test older_bases == ["v1.5.10", "v1", "v1.5"]
    @test "stable" ∉ older_bases

    # The upstream call returns ["v2.0.0", "v2.0"] for this Python-style prerelease.
    @test deploy_bases(
        "v2.0.0a2";
        all_tagged_versions = [v"2.1.0"],
    ) == ["v2.0.0a2"]

    @test deploy_bases("dev"; all_tagged_versions = tagged_versions) == ["dev"]
    @test deploy_bases(
        "previews/PR123";
        all_tagged_versions = tagged_versions,
    ) == ["previews/PR123"]
end
