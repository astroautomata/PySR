using DocumenterVitepress

# Whether this tag is the newest release, and so owns the `stable` alias.
#
# Julia parses Python-style prerelease tags such as v2.0.0a2 as v2.0.0-a2, and
# determine_bases then reports the alpha as owning the v2.0.0 release folder, so only
# plain release tags reach it.
function claims_stable(subfolder; kwargs...)
    occursin(r"^v\d+(\.\d+){0,2}$", subfolder) || return false
    return "stable" in DocumenterVitepress.determine_bases(subfolder; keep = :patch, kwargs...)
end

const STUB_MARKER = "<!--This file is automatically generated by docs/deploy.jl-->"

function stable_redirect_files(page_names, stable_version)
    pages = sort(filter(page -> page ∉ ("index", "404"), page_names))
    files = Dict(
        "stable/index.html" => """$(STUB_MARKER)
<meta http-equiv="refresh" content="0; url=../$(stable_version)/"/>
""",
    )
    for page in pages
        files["stable/$(page).html"] = """$(STUB_MARKER)
<meta http-equiv="refresh" content="0; url=../$(stable_version)/$(page).html"/>
"""
        files["$(page).html"] = """$(STUB_MARKER)
<meta http-equiv="refresh" content="0; url=stable/$(page).html"/>
"""
        files["$(page)/index.html"] = """$(STUB_MARKER)
<meta http-equiv="refresh" content="0; url=../stable/$(page).html"/>
"""
    end
    return files
end

# Stubs left at the root by earlier deployments for pages that no longer exist. Only
# files carrying the marker are candidates, so version folders and hand-written pages are
# never touched, and `stable` is skipped because its deployment replaces it wholesale.
function stale_root_stubs(root, current_paths)
    generated(path) = isfile(path) && startswith(read(path, String), STUB_MARKER)
    stale = String[]
    for entry in readdir(root)
        entry == "stable" && continue
        path = joinpath(root, entry)
        if isdir(path)
            nested = joinpath(entry, "index.html")
            nested in current_paths && continue
            generated(joinpath(root, nested)) && push!(stale, nested)
        elseif endswith(entry, ".html")
            entry in current_paths && continue
            generated(path) && push!(stale, entry)
        end
    end
    return sort(stale)
end
